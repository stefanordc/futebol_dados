-- Estratégias editáveis do Nostradamus: fonte canônica no Supabase.
CREATE TABLE IF NOT EXISTS public.nostradamus_estrategias (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome text NOT NULL CHECK(length(btrim(nome)) BETWEEN 1 AND 80),
 objetivo text NOT NULL,
 corte date NOT NULL,
 jogos text NOT NULL CHECK(jogos IN ('5','10','20','temporada')),
 campeonato_id integer REFERENCES public.campeonatos(id),
 condicoes jsonb NOT NULL CHECK (jsonb_typeof(condicoes)='array' AND jsonb_array_length(condicoes) BETWEEN 1 AND 10),
 odd_hipotetica numeric(12,4),
 comissao_pct numeric(5,2) NOT NULL DEFAULT 2 CHECK(comissao_pct BETWEEN 0 AND 30),
 versao integer NOT NULL DEFAULT 1 CHECK(versao>=1),
 criado_em timestamptz NOT NULL DEFAULT now(),
 atualizado_em timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT nostradamus_odd_positiva CHECK(odd_hipotetica IS NULL OR odd_hipotetica BETWEEN 1.01 AND 1000)
);
CREATE UNIQUE INDEX IF NOT EXISTS nostradamus_estrategias_nome_unq
 ON public.nostradamus_estrategias(lower(btrim(nome)));
CREATE INDEX IF NOT EXISTS nostradamus_estrategias_atualizado_idx
 ON public.nostradamus_estrategias(atualizado_em DESC);
ALTER TABLE public.nostradamus_estrategias ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.nostradamus_estrategias FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON SEQUENCE public.nostradamus_estrategias_id_seq FROM PUBLIC,anon,authenticated,service_role;
